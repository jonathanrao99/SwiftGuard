const fs = require('fs');
const path = require('path');

// Load test configuration
const config = require('./load-test-config.json');

// Create reports directory
const reportsDir = path.join(__dirname, 'reports', new Date().toISOString().split('T')[0]);
if (!fs.existsSync(reportsDir)) {
  fs.mkdirSync(reportsDir, { recursive: true });
}

